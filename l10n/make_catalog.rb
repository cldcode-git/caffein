  warn "Missing English for:\n" + missing.join("\n")
  exit 1
end
extra = EN.keys - keys
warn "Unused translations: #{extra.size}\n#{extra.join("\n")}" unless extra.empty?

def unit(v) { "stringUnit" => { "state" => "translated", "value" => v } } end

# Format specifiers must survive translation (order may change via %1$@).
def specs(s)
  s.scan(/%(?:\d+\$)?(?:lld|ld|d|@|lf|f)/).map { |x| x.sub(/\d+\$/, "") }.sort
end

problems = []
strings = {}
keys.each do |k|
  locs = { "en" => unit(EN[k]), "tr" => unit(k) }
  TRANSLATIONS.each do |code, t|
    v = t.dig("strings", k)
    if v.nil? || v.strip.empty?
      problems << "#{code}: missing #{k[0, 60]}"
      next
    end
    problems << "#{code}: specifiers #{k[0, 60]}" if specs(v) != specs(k)
    problems << "#{code}: bold markers #{k[0, 60]}" if v.scan("**").size != k.scan("**").size
    locs[code] = unit(v)
  end
  strings[k] = { "localizations" => locs }
end
unless problems.empty?
  warn "Translation problems (#{problems.size}):\n" + problems.first(60).join("\n")
  exit 2 if ENV["STRICT"]
end
File.write(out_file, JSON.pretty_generate({ "sourceLanguage" => "tr", "strings" => strings, "version" => "1.0" }) + "\n")

